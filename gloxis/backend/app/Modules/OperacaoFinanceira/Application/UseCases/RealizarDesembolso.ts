import { type IDesembolsoRepository } from '../../Domain/Repositories/IDesembolsoRepository.js'
import { Desembolso } from '../../Domain/Entities/Desembolso.js'
import { type IPagamentoRepository } from '../../Domain/Repositories/IPagamentoRepository.js'
import { Pagamento } from '../../Domain/Entities/Pagamento.js'
import { type ISolicitacaoCreditoRepository } from '../../../SolicitacaoCredito/Domain/Repositories/ISolicitacaoCreditoRepository.js'
import { type IProdutoCreditoRepository } from '../../../ProdutoFinanceiro/Domain/Repositories/IProdutoCreditoRepository.js'
import { SimuladorCreditoService } from '../../../SolicitacaoCredito/Domain/Services/SimuladorCreditoService.js'

export class RealizarDesembolso {
  constructor(
    private desembolsoRepo: IDesembolsoRepository,
    private solicitacaoRepo: ISolicitacaoCreditoRepository,
    private produtoRepo: IProdutoCreditoRepository,
    private pagamentoRepo: IPagamentoRepository
  ) {}

  async execute(
    solicitacaoId: number,
    metodo: 'TRANSFERENCIA' | 'DINHEIRO' | 'CHEQUE',
    comprovantePath: string | null
  ): Promise<Desembolso> {
    const solicitacao = await this.solicitacaoRepo.findById(solicitacaoId)

    if (!solicitacao) {
      throw new Error('Solicitação de crédito não encontrada.')
    }

    if (solicitacao.status !== 'APROVADO') {
      throw new Error('Apenas solicitações aprovadas podem ser desembolsadas.')
    }

    const existingDesembolso = await this.desembolsoRepo.findBySolicitacaoId(solicitacaoId)
    if (existingDesembolso && existingDesembolso.status === 'REALIZADO') {
      throw new Error('Já existe um desembolso realizado para esta solicitação.')
    }

    // For now, assuming product 1 is the default microcredit
    const produto = await this.produtoRepo.findById(1)
    if (!produto) throw new Error('Produto de crédito associado não encontrado.')

    // 1. Criar o desembolso
    const desembolso = new Desembolso(
      0, // ID mock, will be generated by DB
      solicitacaoId,
      solicitacao.valor,
      metodo,
      comprovantePath,
      'REALIZADO',
      new Date(),
      new Date(),
      new Date()
    )

    const savedDesembolso = await this.desembolsoRepo.create(desembolso)

    // 2. Gerar o cronograma de parcelas e salvar os Pagamentos como PENDENTE
    const simulador = new SimuladorCreditoService()
    const { cronograma } = simulador.simular(produto, solicitacao.valor, solicitacao.parcelas)

    for (const parcela of cronograma) {
      const dataVencimento = new Date()
      dataVencimento.setMonth(dataVencimento.getMonth() + parcela.mes)

      const pagamentoPendente = new Pagamento(
        0,
        solicitacaoId,
        parcela.mes,
        parcela.valorParcela,
        0,
        0,
        'TRANSFERENCIA', // default, it doesn't matter until it's paid
        null,
        'PENDENTE',
        dataVencimento,
        null,
        new Date(),
        new Date()
      )

      await this.pagamentoRepo.create(pagamentoPendente)
    }

    return savedDesembolso
  }
}
