import { AnaliseAprovacao } from '../../Domain/Entities/AnaliseAprovacao.js'
import { type SolicitacaoCredito } from '../../../SolicitacaoCredito/Domain/Entities/SolicitacaoCredito.js'

/**
 * Domain Service responsible for calculating the credit score and
 * determining the approval status of a credit request.
 */
export class MotorDeScore {
  public analisar(solicitacao: SolicitacaoCredito): AnaliseAprovacao {
    let score = 0
    let motivo: string | undefined

    // Simulated Business Rules
    // Rule 1: High value requests have stricter scores.
    if (solicitacao.valor > 10000) {
      score += 30 // base score for high value
    } else {
      score += 60 // base score for low value
    }

    // Rule 2: Shorter installments yield better score (less risk)
    if (solicitacao.parcelas <= 12) {
      score += 20
    } else {
      score += 5
    }

    // Cap score at 100
    score = Math.min(score, 100)

    const decision = score >= 60 ? 'APROVADO' : 'REJEITADO'
    if (decision === 'REJEITADO') {
      motivo = 'Score insuficiente baseado no valor e parcelamento.'
    }

    return new AnaliseAprovacao(
      0, // ID will be generated by the database
      solicitacao.id,
      score,
      decision,
      motivo,
      new Date(),
      new Date()
    )
  }
}
